from v2_observe.simulator import Market
from v2_observe.export import write_dataset
sys.path.insert(0,str(Path(__file__).resolve().parent))
from checks import instrumented_run, assert_equivalent, diagnostic_invariants


def csv_signatures(tables):
    return {name+'.csv':hashlib.sha256(frame.to_csv(index=False).encode('utf-8')).hexdigest()
            for name,frame in tables.items()}


def one(job):
    scenario,seed,root=job
    cfg=C.load(ROOT/f'config/scenarios/scenario_{scenario}.yaml')
    w=W.build(cfg,seed)
    world_hash=digest_world(w)
    ends={a['auction_id']:a['default_end_at'] for a in w.auctions}
    reference=None
    csv_reference=None
    timings={}
    checks={}
    for label,cls,kwargs in [('audit',AuditMarket,{}),('off',Market,{'observer':False}),('on',Market,{'observer':True})]:
        m=cls(w,ends,seed,cfg.get('close_rule','hard'),**kwargs)
        fingerprint=instrumented_run(m)
        tables=to_tables(w,m,cfg,'seller_default')
        serialized=csv_signatures(tables)
        timings[label]=fingerprint['instrumented_seconds']
        if reference is None:
            reference=fingerprint
            csv_reference=serialized
        else:
            assert_equivalent(reference,fingerprint)
            assert serialized==csv_reference
        assert world_hash==digest_world(w)
        checks[label+'_world_unchanged']=True
        checks[label+'_parent_state_equal']=fingerprint['state']==reference['state']
        checks[label+'_RNG_stream_equal']=fingerprint['rng_sha256']==reference['rng_sha256']
        checks[label+'_heap_operation_stream_equal']=fingerprint['queue_sha256']==reference['queue_sha256']
        checks[label+'_11_CSV_equal']=serialized==csv_reference
        if label=='on':
            diagnostics=diagnostic_invariants(m)
            destination=Path(root)/f'scenario_{scenario}/seed_{seed}/v2-a-observe-v1'
            write_dataset(w,m,destination,seed,ROOT/f'config/scenarios/scenario_{scenario}.yaml')
            # Compare actual generated bytes to the frozen audit-fix manifest,
            # not merely to a fresh execution of the same parent implementation.
            manifest=json.loads((ROOT/'AUDIT_FIX_v1.json').read_text(encoding='utf-8'))
            prefix=f'data/experiments/audit-20261030/regression/scenario_{scenario}/seed_{seed}/audit-fix-v1/'
            frozen={k[len(prefix):]:v for k,v in manifest['corrected_csv_sha256'].items() if k.startswith(prefix)}
            assert len(frozen)==11
            actual={k:hashlib.sha256((destination/k).read_bytes()).hexdigest() for k in frozen}
            assert actual==frozen, 'Frozen audit dataset byte mismatch'
            checks['frozen_audit_11_CSV_bytes_equal']=True
            validation=structural(original.load(destination),cfg)
            assert validation['all_pass']
            checks['existing_extended_structure']=True
            diagnostic_bytes=sum(p.stat().st_size for p in (destination/'diagnostics').glob('*.csv'))
            result={'checks':checks,'all_pass':all(checks.values()),'diagnostics':diagnostics,
                    'structure':validation,'RNG_calls':fingerprint['counts'],'RNG_sha256':fingerprint['rng_sha256'],
                    'heap_sha256':fingerprint['queue_sha256'],'parent_attribute_hashes':fingerprint['state'],
                    'instrumented_seconds_not_benchmark':timings,'diagnostic_csv_bytes':diagnostic_bytes,
                    'bids':len(m.bids),'events':len(m.events),'wtp_cache_entries':len(m.wtp_log)}
        del m,tables,fingerprint
        gc.collect()
    return f'scenario_{scenario}/seed_{seed}',result


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--report',type=Path,required=True)
    p.add_argument('--workers',type=int,default=2)
    a=p.parse_args()
    allowed=(ROOT/'data/experiments/v2a-20261031').resolve()
    out=a.out.resolve()
    report=a.report.resolve()
    if out==allowed or not out.is_relative_to(allowed) or out.exists():
        raise ValueError('Use a NEW v2a experiment subdirectory')
    if report.exists() or not report.is_relative_to((ROOT/'validation/v2_observe').resolve()):
        raise ValueError('Use a NEW report inside validation/v2_observe')
    out.mkdir(parents=True)
    result={}
    jobs=[(s,seed,str(out)) for s in 'ABCDEF' for seed in (1,2,3)]
    with ProcessPoolExecutor(a.workers) as pool:
        for f in as_completed([pool.submit(one,j) for j in jobs]):
            key,value=f.result()
            result[key]=value
            print(key,'ALL PASS',value['all_pass'],'views',value['diagnostics']['actual_views'],flush=True)
    output={'n_datasets':len(result),'all_pass':len(result)==18 and all(r['all_pass'] for r in result.values()),
            'comparison':'audit-fix-v1 vs V2-A OFF vs V2-A ON on identical World/seed/default policy',
            'frozen_audit_CSV_checked':18*11,'datasets':dict(sorted(result.items()))}
    report.parent.mkdir(parents=True,exist_ok=True)
    report.write_text(json.dumps(output,indent=2,allow_nan=False),encoding='utf-8')
    print('18-DATASET REGRESSION:',output['all_pass'],flush=True)
    if not output['all_pass']:
        raise SystemExit(1)


if __name__=='__main__':
    main()
